"""RQ1_summary.md, generated from the final tables only (never by hand): the pre-stated failure conditions of
plan 4 answered one by one, plus the pre-registered secondary analysis. Every number is read from a table.
"""

from __future__ import annotations

from typing import Any

import pandas as pd

DISTANCE_PREFIXES = ("euclid_", "lof_")


def _ci(row: pd.Series, col: str) -> str:
    return f"{row[col]:.4f} [{row[col + '_lo']:.4f}, {row[col + '_hi']:.4f}]"


def _sign(lo: float, hi: float) -> str:
    if lo > 0:
        return "MFSI better"
    return "MFSI worse" if hi < 0 else "no difference (CI includes 0)"


def _header(cfg: dict[str, Any], meta: dict[str, Any]) -> list[str]:
    lines = [f"# RQ1 summary ({cfg['profile']}, split {meta['split']})", ""]
    if cfg["profile"] != "full":
        lines += [f"**THROW-AWAY: {cfg['profile']} profile, plumbing check only. Never report.**", ""]
    lines += [f"- commit {meta['commit']}; seeds {meta['seeds']}; B = {cfg['eval']['bootstrap_B']}.",
              f"- Generated by scripts/41_run_rq1_final.py from outputs/{cfg['profile']}/tables/.", ""]
    return lines


def _headline(m: pd.DataFrame) -> list[str]:
    ref, msp = m.loc["mfsi"], m.loc["msp"]
    return ["## Headline (macro AURC over findings; lower is better)", "",
            f"- MFSI: {_ci(ref, 'aurc')}; random {ref['aurc_random']:.4f}; oracle {ref['aurc_oracle']:.4f}",
            f"- MSP: {_ci(msp, 'aurc')}; MSP - MFSI {_ci(msp, 'aurc_minus_ref')} -> "
            f"{_sign(msp['aurc_minus_ref_lo'], msp['aurc_minus_ref_hi'])}", ""]


def _cross_modal(cm: pd.DataFrame) -> list[str]:
    holds = cm.loc[cm["claim_holds"], "finding"].tolist()
    two = cm.loc[cm["stratum"] == "two_witness", "finding"].tolist()
    answer = "yes, for the findings listed" if holds else "no (failure condition met)"
    return ["## (a) Does cross-modal MFSI beat single-modality MFSI? (decisive)", "",
            "- Pre-stated rule: the CI of AURC(best single modality) - AURC(MFSI) excludes 0 for MFSI.",
            f"- Two-witness findings (text informative): {len(two)} ({', '.join(two) or 'none'}).",
            f"- The claim holds for {len(holds)} of {len(cm)} findings: {', '.join(holds) or 'none'}.",
            f"- Answer: {answer}.", ""]


def _agreement(spread: pd.DataFrame, inert_sd: float) -> list[str]:
    two = spread[spread["stratum"] == "two_witness"]
    inert = int((two["sd"] < inert_sd).sum())
    if not len(two):
        answer = "not assessable (no two-witness finding)"
    else:
        answer = "inert (failure condition met)" if inert > len(two) / 2 else "not inert"
    return ["## (b) Is the agreement term inert?", "",
            f"- A_cos sd below {inert_sd} in {inert} of {len(two)} two-witness finding-seeds "
            "(A enters R only for two-witness findings).", f"- Answer: {answer}.", ""]


def _distance(m: pd.DataFrame, ablations: pd.DataFrame) -> list[str]:
    dist = [s for s in m.index if s.startswith(DISTANCE_PREFIXES)]
    rows = [f"  - {s}: {_ci(m.loc[s], 'aurc_minus_ref')} -> "
            f"{_sign(m.loc[s, 'aurc_minus_ref_lo'], m.loc[s, 'aurc_minus_ref_hi'])}" for s in dist]
    ab = ablations.set_index("variant")
    var = [f"  - MFSI with {v} distance: variant - default {ab.loc[v, 'minus_default']:.4f} "
           f"[{ab.loc[v, 'minus_default_lo']:.4f}, {ab.loc[v, 'minus_default_hi']:.4f}]"
           for v in ("Euclidean", "LOF") if v in ab.index and pd.notna(ab.loc[v, "minus_default"])]
    beats = bool(dist) and all(m.loc[s, "aurc_minus_ref_lo"] > 0 for s in dist)
    answer = "yes, against every Euclidean / LOF baseline" if beats else "no (failure condition met)"
    return ["## (c) Does Mahalanobis (MFSI) beat Euclidean / LOF?", "",
            "- Baselines (score - MFSI, macro AURC):", *rows,
            "- Sensitivity rows (MFSI's own distance swapped):", *(var or ["  - not available"]),
            f"- Answer: {answer}.", ""]


def _sensitivity(ablations: pd.DataFrame) -> list[str]:
    flagged = ablations.loc[ablations["changes_conclusion"].fillna(False).astype(bool), "variant"].tolist()
    not_run = ablations.loc[ablations["status"] == "not run", "variant"].tolist()
    return ["## Sensitivity", "", f"- Rows changing a headline conclusion: {', '.join(flagged) or 'none'}.",
            f"- Rows not run: {', '.join(not_run) or 'none'}.", ""]


def _added_value(am: pd.Series, bm: pd.Series) -> list[str]:
    if am["n_findings"]:
        verdict = "added value" if am["added_value"] else "no added value"
        a = (f"macro delta-AURC {am['delta']:.4f} [{am['delta_lo']:.4f}, {am['delta_hi']:.4f}] over "
             f"{int(am['n_findings'])} findings -> {verdict}")
    else:
        a = "no eligible finding"
    if bm["n_findings"]:
        verdict = "adds information" if bm["adds_information"] else "no added information"
        b = (f"macro stratified AUROC {bm['stratified_auroc']:.4f} [{bm['lo']:.4f}, {bm['hi']:.4f}] over "
             f"{int(bm['n_findings'])} findings -> {verdict}")
    else:
        b = "no finding enters"
    return ["## Pre-registered secondary analysis: added value beyond MSP", "",
            f"- (a) combined [MSP, MFSI] vs MSP: {a}.", f"- (b) MFSI within MSP quintiles: {b}.", ""]


def _degrade(t: dict[str, pd.DataFrame]) -> list[str]:
    head = ["## Degrade-one-modality (face validity)", ""]
    if "controls_degrade" not in t:
        return [*head, "- not run in this final run (see the run log).", ""]
    ok = t["controls_degrade"].groupby("variant")[["own_margin_falls", "other_margin_unchanged"]].first()
    return [*head, f"- Own margin falls in {int(ok['own_margin_falls'].sum())} of {len(ok)} degradations; "
            f"other margin unchanged in {int(ok['other_margin_unchanged'].sum())} of {len(ok)}.", ""]


def build(cfg: dict[str, Any], t: dict[str, pd.DataFrame], meta: dict[str, Any]) -> str:
    m = t["rq1_main"].set_index("score")
    lines = [*_header(cfg, meta), *_headline(m), *_cross_modal(t["rq1_cross_modal"]),
             *_agreement(t["controls_agreement_spread"], cfg["mfsi"]["inert_sd"]),
             *_distance(m, t["rq1_ablations"]), *_sensitivity(t["rq1_ablations"]),
             *_added_value(t["added_value_a_macro"].iloc[0], t["added_value_b_macro"].iloc[0]), *_degrade(t)]
    return "\n".join(lines) + "\n"
