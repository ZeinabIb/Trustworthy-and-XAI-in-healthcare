"""Reading the raw metadata table and auditing its columns (Phase 1.1).

The audit never writes report text: text columns are summarised by null rate and length only.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import pandas as pd

from mfsi_cxr.data.text_inputs import FORBIDDEN_INDEX_ALWAYS

ALLOWED_INDEX, ALLOWED_PRIOR_ONLY, FORBIDDEN, NON_TEXT = (
    "ALLOWED_INDEX", "ALLOWED_PRIOR_ONLY", "FORBIDDEN", "NON_TEXT",
)
# A string column whose mean length exceeds this is treated as free text (no examples shown).
FREE_TEXT_MEAN_LEN = 40
EXAMPLE_MAX_CHARS = 40


def metadata_path(root: Path, cfg: dict[str, Any]) -> Path:
    return root / cfg["data"]["metadata_file"]


def read_metadata(root: Path, cfg: dict[str, Any], columns: list[str] | None = None) -> pd.DataFrame:
    """Read the metadata table, optionally only `columns` (the IO-level allowlist)."""
    path = metadata_path(root, cfg)
    if path.suffix == ".parquet":
        return pd.read_parquet(path, columns=columns)
    return pd.read_csv(path, usecols=columns, low_memory=False)


def structural_columns(cfg: dict[str, Any]) -> list[str]:
    """Non-text columns needed to build the index."""
    return list(cfg["data"]["columns"].values())


def is_text_column(name: str, series: pd.Series) -> bool:
    if name.startswith("section_") or name in FORBIDDEN_INDEX_ALWAYS:
        return True
    if series.dtype != object:
        return False
    lengths = series.dropna().astype(str).str.len()
    return bool(len(lengths)) and lengths.mean() > FREE_TEXT_MEAN_LEN


def classify_column(name: str, series: pd.Series, cfg: dict[str, Any]) -> str:
    sections = cfg["data"]["text_sections"]
    if name in sections["allowed_index"]:
        return ALLOWED_INDEX
    if name in sections["allowed_prior"]:
        return ALLOWED_PRIOR_ONLY
    if name in structural_columns(cfg):
        return NON_TEXT
    if is_text_column(name, series):
        return FORBIDDEN  # allowlist: unlisted text is forbidden by default
    return NON_TEXT


def audit(meta: pd.DataFrame, cfg: dict[str, Any]) -> pd.DataFrame:
    rows = []
    for name in meta.columns:
        s = meta[name]
        cls = classify_column(name, s, cfg)
        non_null = s.dropna()
        if cls == NON_TEXT:
            example = str(non_null.iloc[0])[:EXAMPLE_MAX_CHARS] if len(non_null) else ""
        else:
            mean_len = non_null.astype(str).str.len().mean() if len(non_null) else 0.0
            example = f"<text, mean {mean_len:.0f} chars>"
        rows.append(
            {
                "column": name,
                "dtype": str(s.dtype),
                "null_rate": round(float(s.isna().mean()), 4),
                "n_unique": int(s.nunique()),
                "class": cls,
                "example": example,
            }
        )
    return pd.DataFrame(rows)


def audit_markdown(table: pd.DataFrame, n_rows: int, profile: str) -> str:
    header = "| column | dtype | null_rate | n_unique | class | example |\n|---|---|---|---|---|---|\n"
    body = "".join(
        f"| `{r.column}` | {r.dtype} | {r.null_rate} | {r.n_unique} | {r['class']} | {r.example} |\n"
        for _, r in table.iterrows()
    )
    return (
        f"# DATA_SCHEMA ({profile})\n\nGenerated by scripts/10_audit_data.py from {n_rows} metadata rows.\n"
        "Text columns show length only. Classes come from configs/data.yaml (allowlist); any text column\n"
        "not listed there is FORBIDDEN by default.\n\n" + header + body
    )
